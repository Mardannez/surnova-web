export const formatPrice = (price: number): string => {
  return `L ${price.toLocaleString('es-HN')}`;
};

export const getDiscountedPrice = (original: number, discount: number): number => {
  return Math.round(original * (1 - discount / 100));
};

export const getFeaturedProducts = (): Product[] => PRODUCTS.filter(p => p.featured);
export const getGamingProducts = (): Product[] => PRODUCTS.filter(p => p.gaming);
export const getOfferProducts = (): Product[] => PRODUCTS.filter(p => p.offer);
